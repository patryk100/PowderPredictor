/**
 * Generate 72-hour realistic meteorological time-series for a resort during autumn/fall
 * (Freezing levels aloft at 5,000-6,500 ft, mild diurnal cycle, trace high-elevation summit flurries)
 */
export function generate72hTimeSeries(
  resort: Partial<ResortForecast>,
  totalSnow: number,
  baseFreezing: number
): HourlyForecastStep[] {
  const steps: HourlyForecastStep[] = [];
  const now = new Date();
  let cumulative = 0;

  for (let h = 0; h <= 72; h += 3) {
    const t = new Date(now.getTime() + h * 3600 * 1000);
    // Autumn diurnal fluctuation: rises in afternoon (+300ft), dips overnight (-300ft)
    const diurnal = Math.sin(((h + 6) / 24) * 2 * Math.PI) * 350;
    const freezeFt = Math.round(baseFreezing + diurnal);

    // Summit & Base temperatures
    const summitFt = resort.summitFt ?? 3800;
    const baseFt = resort.baseFt ?? 1400;
    const lapseRate = 3.5; // °F per 1000ft

    // Base temp typically 48°F to 58°F in fall
    const baseTempF = Math.round(32 + ((freezeFt - baseFt) / 1000) * lapseRate);
    const summitTempF = Math.round(baseTempF - ((summitFt - baseFt) / 1000) * lapseRate);
    const summitTempC = Math.round(((summitTempF - 32) * 5) / 9);

    // DGZ check: -12°C to -18°C (approx 10°F to 0°F) - inactive in mid-October
    const inDGZ = summitTempC >= -18 && summitTempC <= -12;

    // Precipitation phase determination for autumn
    let phase: "rain" | "mixed" | "dense_snow" | "blower_powder" | "clear" = "clear";
    let incSnow = 0;

    if (h >= 18 && h <= 39) {
      // Periodic autumn trough passage
      if (summitTempF > 35) {
        phase = "rain";
      } else if (summitTempF >= 31) {
        phase = "mixed";
        incSnow = totalSnow > 0 ? Math.round((totalSnow / 8) * 10) / 10 : 0;
      } else {
        phase = "dense_snow";
        incSnow = totalSnow > 0 ? Math.round((totalSnow / 6) * 10) / 10 : 0;
      }
    }
    cumulative = Math.round((cumulative + incSnow) * 10) / 10;

    const windSpeed = 10 + (h % 9);
    const windGust = windSpeed + 12;

    steps.push({
      hourOffset: h,
      timestamp: t.toISOString(),
      freezingLevelElevationFt: freezeFt,
      summitTempF,
      midTempF: Math.round((baseTempF + summitTempF) / 2),
      baseTempF,
      summitTempC,
      phase,
      snowfallInches: incSnow,
      cumulativeSnowInches: cumulative,
      windSpeedMph: windSpeed,
      windGustMph: windGust,
      inDGZ,
    });
  }

  return steps;
}

